'use strict';

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const { createEngineContext } = require('../../src/main/engine-context');
const { generateAll } = require('../../src/engine/configGen');
const paths = require('../../src/engine/paths');

// Mirrors test/main/engine-context-apikey.test.js's withFakeHome — the only
// sanctioned way (per CLAUDE.md) to point createEngineContext() at a
// throwaway directory instead of this machine's real ~/.config/claude-conduit.
function withFakeHome(fn) {
  const homeDir = fs.mkdtempSync(path.join(os.tmpdir(), 'nim-engine-context-regen-test-'));
  const argvHadDev = process.argv.includes('--dev');
  const originalTestHome = process.env.NIM_PROXY_TEST_HOME;
  if (!argvHadDev) process.argv.push('--dev');
  process.env.NIM_PROXY_TEST_HOME = homeDir;
  return Promise.resolve()
    .then(() => fn(homeDir))
    .finally(() => {
      if (!argvHadDev) {
        const idx = process.argv.indexOf('--dev');
        if (idx !== -1) process.argv.splice(idx, 1);
      }
      if (originalTestHome === undefined) delete process.env.NIM_PROXY_TEST_HOME;
      else process.env.NIM_PROXY_TEST_HOME = originalTestHome;
      fs.rmSync(homeDir, { recursive: true, force: true });
    });
}

function fakeSafeStorage() {
  return {
    isEncryptionAvailable: () => true,
    encryptString: (s) => Buffer.from(`enc:${s}`, 'utf8'),
    decryptString: (b) => b.toString('utf8').slice(4),
  };
}

// NCOW-30: createEngineContext hardcodes require('pm2') for its REAL
// pm2Control (see engine-context.js) — every existing test in this repo
// (engine-context-apikey.test.js, shutdown.test.js's own fakePm2 pattern)
// carefully avoids exercising any pm2-touching code path for exactly that
// reason: connecting to/spawning a real system pm2 daemon during `npm test`
// is not something any test here does. engine-context.js's optional
// deps.pm2Control override (added for this task) lets this test observe the
// NCOW-30 stale-config-regeneration wiring end to end without ever touching
// a real pm2 daemon.
function fakePm2Control({ status = 'not-installed' } = {}) {
  const calls = { getStatus: 0, startOrRestart: [] };
  return {
    calls,
    pm2Control: {
      APP_NAME: 'litellm-nim',
      getStatus: async () => {
        calls.getStatus += 1;
        return { status };
      },
      startOrRestart: async (opts) => {
        calls.startOrRestart.push(opts);
        return { ok: true };
      },
    },
  };
}

/**
 * Lays down exactly what a real pre-NCOW-30 install has on disk: a config
 * directory generated by generateAll() (version-agnostic — this is honestly
 * what an old build's setup wizard produced) plus a manifest.json with no
 * generated_by_version field at all, since that field never existed before
 * this task.
 */
function seedStaleInstall(homeDir) {
  const configDir = paths.resolveConfigDir({ homedir: homeDir });
  const files = paths.getFilePaths(configDir);

  generateAll({
    files,
    primaryModelId: 'meta/llama-3.1-8b-instruct',
    smallModelId: 'meta/llama-3.1-8b-instruct',
    nimBaseUrl: undefined,
    port: 4000,
    litellmAbsPath: '/usr/local/bin/litellm',
    nvidiaApiKey: 'nvapi-old-install',
  });

  const manifest = {
    version: 1,
    port: 4000,
    primary_model: 'meta/llama-3.1-8b-instruct',
    small_model: 'meta/llama-3.1-8b-instruct',
    nim_base_url: null,
    litellm_path: '/usr/local/bin/litellm',
    pm2_app: 'litellm-nim',
    cli_configured: false,
    secret_store_backend: 'electron-safeStorage',
  };
  fs.writeFileSync(files.manifestJson, JSON.stringify(manifest, null, 2) + '\n', 'utf8');

  return files;
}

test('createEngineContext: an upgraded install (stale generated config, older/no version marker) regenerates on launch without re-running setup', async () => {
  await withFakeHome(async (homeDir) => {
    const files = seedStaleInstall(homeDir);
    const { pm2Control, calls } = fakePm2Control({ status: 'not-installed' });

    const context = createEngineContext({
      safeStorage: fakeSafeStorage(),
      userDataDir: path.join(homeDir, 'userData'),
      appDataDir: path.join(homeDir, 'appData'),
      broadcast: () => {},
      appVersion: '0.2.0',
      pm2Control,
    });

    const result = await context.configRegeneration;
    assert.deepEqual(result, { regenerated: true });

    const manifestAfter = JSON.parse(fs.readFileSync(files.manifestJson, 'utf8'));
    assert.equal(manifestAfter.generated_by_version, '0.2.0');

    const cjs = fs.readFileSync(files.ecosystemConfig, 'utf8');
    assert.match(cjs, /interpreter:\s*process\.execPath,/);
    assert.match(cjs, /PYTHONIOENCODING/);

    // Not running at launch (the ordinary case — see NCOW-4) — no restart.
    assert.equal(calls.getStatus, 1);
    assert.equal(calls.startOrRestart.length, 0);
  });
});

test('createEngineContext: AC#2 — regenerating while the proxy is already running restarts it the same way proxy.start()/restart() do', async () => {
  await withFakeHome(async (homeDir) => {
    const files = seedStaleInstall(homeDir);
    const { pm2Control, calls } = fakePm2Control({ status: 'running' });

    const context = createEngineContext({
      safeStorage: fakeSafeStorage(),
      userDataDir: path.join(homeDir, 'userData'),
      appDataDir: path.join(homeDir, 'appData'),
      broadcast: () => {},
      appVersion: '0.2.0',
      pm2Control,
    });

    const result = await context.configRegeneration;
    assert.deepEqual(result, { regenerated: true });

    assert.equal(calls.startOrRestart.length, 1);
    assert.deepEqual(calls.startOrRestart[0], {
      ecosystemConfigPath: files.ecosystemConfig,
      port: 4000,
      outLog: files.outLog,
      errLog: files.errLog,
    });
  });
});

test('createEngineContext: a fresh install (no manifest yet) never touches pm2, regardless of appVersion', async () => {
  await withFakeHome(async (homeDir) => {
    const { pm2Control, calls } = fakePm2Control();

    const context = createEngineContext({
      safeStorage: fakeSafeStorage(),
      userDataDir: path.join(homeDir, 'userData'),
      appDataDir: path.join(homeDir, 'appData'),
      broadcast: () => {},
      appVersion: '0.2.0',
      pm2Control,
    });

    const result = await context.configRegeneration;
    assert.deepEqual(result, { regenerated: false, reason: 'up-to-date' });
    assert.equal(calls.getStatus, 0);
    assert.equal(calls.startOrRestart.length, 0);
  });
});

test('createEngineContext: an already up-to-date install is a no-op on the next launch', async () => {
  await withFakeHome(async (homeDir) => {
    const files = seedStaleInstall(homeDir);
    const manifest = JSON.parse(fs.readFileSync(files.manifestJson, 'utf8'));
    manifest.generated_by_version = '0.2.0';
    fs.writeFileSync(files.manifestJson, JSON.stringify(manifest, null, 2) + '\n', 'utf8');
    const before = fs.readFileSync(files.ecosystemConfig, 'utf8');

    const { pm2Control, calls } = fakePm2Control({ status: 'running' });
    const context = createEngineContext({
      safeStorage: fakeSafeStorage(),
      userDataDir: path.join(homeDir, 'userData'),
      appDataDir: path.join(homeDir, 'appData'),
      broadcast: () => {},
      appVersion: '0.2.0',
      pm2Control,
    });

    const result = await context.configRegeneration;
    assert.deepEqual(result, { regenerated: false, reason: 'up-to-date' });
    assert.equal(calls.getStatus, 0, 'must never check proxy status when nothing needs regenerating');
    assert.equal(fs.readFileSync(files.ecosystemConfig, 'utf8'), before);
  });
});

